/** An alternative capture/check the user might try instead of the line move, with the engine's best reply. */
export interface Alt { san: string; reply: string; eval: number }
/** A highlight drawn on the board: an arrow when `to` is set, a ring around `from` otherwise. */
export interface Shape { from: string; to?: string; color?: 'green' | 'red' | 'blue' | 'yellow' }
/** A position to show with shapes on it. `ply` = number of moves played from the start (0 = start position). */
export interface PlanBoard { ply: number; shapes: Shape[] }
/** `why` is hand-written text for a specific wrong move (keyed by SAN); `caps` is generated by `npm run evals`. */
export interface Move { san: string; note: string; eval: number; why?: Record<string, string>; caps?: Alt[]; shapes?: Shape[] /* shown in Learn after this move */ }
export interface Variation { id: string; name: string; strategy: string; board?: PlanBoard; moves: Move[] }
export interface Opening {
  id: string; name: string; color: 'white' | 'black'; summary: string; status: 'draft' | 'reviewed';
  goal: { title: string; text: string; plans: string[]; board?: PlanBoard & { variation: string } };
  variations: Variation[];
}
